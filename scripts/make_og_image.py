#!/usr/bin/env python3
"""Generate the social share card (og:image) with no dependencies.

The site declared twitter:card=summary_large_image while no og:image existed
anywhere - a share card promising a picture that was not there. Pillow and
ImageMagick are both unavailable here, so this writes the PNG directly:
a pure-Python encoder plus a hand-built 5x7 bitmap font.

    python3 scripts/make_og_image.py

Writes assets/og-card.png at 1200x630 (the size Twitter/X, LinkedIn,
Slack and Discord all expect).
"""
