def new_canvas():
    return [[BG for _ in range(W)] for _ in range(H)]


def rect(px, x, y, w, h, colour):
    for yy in range(max(0, y), min(H, y + h)):
        row = px[yy]
        for xx in range(max(0, x), min(W, x + w)):
            row[xx] = colour


def draw_text(px, text, x, y, scale, colour, spacing=1):
    cx = x
    for ch in text.upper():
        glyph = FONT.get(ch)
        if glyph is None:
            cx += (5 + spacing) * scale
            continue
        for ry, bits in enumerate(glyph):
            for rx in range(5):
                if bits & (1 << (4 - rx)):
                    rect(px, cx + rx * scale, y + ry * scale, scale, scale, colour)
        cx += (5 + spacing) * scale
    return cx


def text_width(text, scale, spacing=1):
    return len(text) * (5 + spacing) * scale


def write_png(path, px):
    raw = bytearray()
    for row in px:
        raw.append(0)  # filter type 0
        for r, g, b in row:
            raw += bytes((r, g, b))

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(root)
    os.makedirs("assets", exist_ok=True)

    # Read the entry count from the tracker rather than hardcoding it.
    # The first version of this script baked "15 AUDITED CLAIMS" into the
    # image, which would have silently become a lie the moment entry 16
    # shipped - a stale number on the one asset built to travel.
    with open("runway.json") as f:
        entries = json.load(f)["products"]["register_entries"]

    px = new_canvas()

    # accent rule down the left edge
    rect(px, 0, 0, 12, H, ACCENT)

    draw_text(px, "THE AGENT REVENUE REGISTER", 80, 90, 4, ACCENT)

    # headline
    draw_text(px, f"{entries} AUDITED CLAIMS.", 80, 190, 9, FG)
    draw_text(px, "6 WAYS THE NUMBER", 80, 290, 9, FG)
    draw_text(px, "GETS BIGGER.", 80, 390, 9, FG)

    # the number that matters
    rect(px, 80, 500, 620, 3, MUTED)
    draw_text(px, "MY OWN REVENUE: $0.00", 80, 530, 5, FG)
    draw_text(px, "VENTUREBOT.DEV", 80, 585, 3, MUTED)

    write_png("assets/og-card.png", px)
    size = os.path.getsize("assets/og-card.png")
    print(f"wrote assets/og-card.png  {W}x{H}  {size:,} bytes  ({entries} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
